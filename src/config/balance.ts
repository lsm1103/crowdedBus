/**
 * 计分表。
 *
 * 这一套存在的唯一理由：**让"主动参与"严格优于"躲起来不动"**。
 * 旧的名次公式是 `离门距离×4 + 抓扶手×30`，也就是躲在角落抓着扶手全程不动
 * 就是第一名 —— 一个"把对手挤下车"的游戏，最优解是别动。
 *
 * 按 60 秒一局粗算：
 *   坐 25 秒 + 击落 1 人     ≈ 25×10 + 100 + 50 = 400
 *   拽起 2 次座位 + 逼门几下 ≈ 2×92 + 5×15 + 50 ≈ 310（不坐也有正经收益）
 *   纯躲角落抓扶手           ≈ 0 + 0 + 50        = 50
 * 这个差距才是"改过了"的证据。probe 实测（30 局，seatSteal=80）：均衡 647、聪明进攻 649、
 * 无脑推 515、只坐不动 407、躲扶手 ≈ 85。
 */
